"""Replay original demonstrations exactly and record real post-release continuation.

Original HDF5 files are read-only. New suffixes are generated by the preserved PPO
actor, not relabeled scripted demonstrations. The same episode IDs are retained.
"""

import json
from pathlib import Path
import h5py
import numpy as np
import torch
from stable_baselines3 import PPO
from geopolicy.environment import SelectPlace, CAMERAS
from geopolicy.sensors import student_state, camera_packet
from geopolicy.io import save_json
from .config import file_hash
from .metrics import StageTracker
from .resources import ResourceWatch


def augment(recipe):
    original = json.loads(Path("configs/dataset_manifest.json").read_text())
    selected = set(original["selected_train_ids"] + original["selected_validation_ids"])
    out = Path("artifacts/v2/dataset")
    out.mkdir(parents=True, exist_ok=True)
    teacher_path = "artifacts/teacher_selected.zip"
    teacher = PPO.load(teacher_path, device="cpu")
    saved = torch.load(
        "artifacts/main_runs/fusion_s0/best.pt", map_location="cpu", weights_only=False
    )
    save_json(
        "configs/v2/normalization.json", {k: v.tolist() for k, v in saved["normalization"].items()}
    )
    del saved
    env = SelectPlace(cameras=True)
    env.horizon = 280
    watch = ResourceWatch(out, recipe["resource_limits"])
    records = []
    try:
        for record in original["episodes"]:
            if record["episode_id"] not in selected:
                continue
            path = out / Path(record["path"]).name
            if path.exists():
                with h5py.File(path) as f:
                    metadata = json.loads(f.attrs["metadata"])
            else:
                obs = env.reset_scene(record["scene_seed"])
                tracker = StageTracker(recipe["stability"])
                error = 0
                with h5py.File(record["path"]) as source:
                    actions = source["action"][:]
                    states = source["state"][:]
                    for index, action in enumerate(actions):
                        watch.sample()
                        error = max(error, float(np.abs(student_state(obs) - states[index]).max()))
                        obs, _, _, info = env.step(action)
                        tracker.update(env, obs, action, info)
                    assert error < 1e-6, (record["episode_id"], error)
                    suffix = []
                    for _ in range(recipe["data_extension"]["post_release_steps"]):
                        watch.sample()
                        action, _ = teacher.predict(env.teacher_state(), deterministic=True)
                        packet = camera_packet(env, obs)
                        packet.update(
                            state=student_state(obs),
                            action=action.astype(np.float32),
                            instruction_tokens=source["instruction_tokens"][-1],
                        )
                        suffix.append(packet)
                        obs, _, _, info = env.step(action)
                        tracker.update(env, obs, action, info)
                    final = camera_packet(env, obs)
                    metadata = dict(
                        json.loads(source.attrs["metadata"]),
                        version=2,
                        original_hdf5_sha256=record["sha256"],
                        original_frames=len(actions),
                        post_release_frames=len(suffix),
                        prefix_state_replay_max_error=error,
                        post_release_provenance="same_selected_ppo_actor_continuation",
                        post_release_teacher_sha256=file_hash(teacher_path),
                        frames=len(actions) + len(suffix),
                        stable_teacher_continuation=tracker.window.success,
                    )
                    temporary = path.with_suffix(".tmp")
                    with h5py.File(temporary, "w") as destination:
                        destination.attrs["metadata"] = json.dumps(metadata)
                        for key in [
                            "state",
                            "action",
                            "instruction_tokens",
                            "timestamp_s",
                            "world_from_base",
                        ]:
                            destination.create_dataset(
                                key,
                                data=np.concatenate(
                                    [source[key][:], np.stack([r[key] for r in suffix])]
                                ),
                                compression="gzip",
                                shuffle=True,
                            )
                        for camera in CAMERAS:
                            group = destination.create_group(camera)
                            for key in suffix[0][camera]:
                                group.create_dataset(
                                    key,
                                    data=np.concatenate(
                                        [
                                            source[camera + "/" + key][:],
                                            np.stack([r[camera][key] for r in suffix]),
                                        ]
                                    ),
                                    compression="gzip",
                                    shuffle=True,
                                )
                            group.create_dataset(
                                "final_rgb", data=final[camera]["rgb"], compression="gzip"
                            )
                            group.create_dataset(
                                "final_depth_m", data=final[camera]["depth_m"], compression="gzip"
                            )
                    temporary.replace(path)
            records.append(
                dict(
                    record,
                    path=path.as_posix(),
                    sha256=file_hash(path),
                    bytes=path.stat().st_size,
                    original_frames=metadata["original_frames"],
                    post_release_frames=metadata["post_release_frames"],
                    prefix_state_replay_max_error=metadata["prefix_state_replay_max_error"],
                    stable_teacher_continuation=metadata["stable_teacher_continuation"],
                )
            )
            save_json("artifacts/v2/dataset/augmentation_progress.json", records)
            print(
                json.dumps(
                    {
                        "completed": len(records),
                        "episode_id": record["episode_id"],
                        "stable_continuation": metadata["stable_teacher_continuation"],
                    }
                ),
                flush=True,
            )
    finally:
        env.close()
    manifest = dict(
        episodes=records,
        selected_train_ids=original["selected_train_ids"],
        selected_validation_ids=original["selected_validation_ids"],
        test_unlocked=False,
        source_manifest_sha256=file_hash("configs/dataset_manifest.json"),
        augmentation="Original sensor/action prefixes plus 30 actual PPO post-release steps; same 200/21 episode IDs, frozen original normalization",
    )
    assert len(records) == 221
    save_json("configs/v2/dataset_manifest.json", manifest)
    save_json(
        "results/v2/augmentation_summary.json",
        {
            "episodes": len(records),
            "post_release_steps_per_episode": recipe["data_extension"]["post_release_steps"],
            "prefix_state_replay_max_error": max(
                r["prefix_state_replay_max_error"] for r in records
            ),
            "stable_teacher_continuations": sum(r["stable_teacher_continuation"] for r in records),
            "bytes": sum(r["bytes"] for r in records),
            "source_v1_files_unchanged": True,
        },
    )
